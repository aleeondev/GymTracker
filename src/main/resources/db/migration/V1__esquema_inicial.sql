-- Biblioteca de ejercicios. usuario_id vacío = ejercicio común para todos.
create table ejercicios (
    id             bigint generated by default as identity primary key,
    usuario_id     uuid,
    nombre         varchar(255),
    grupo_muscular varchar(255),
    equipamiento   varchar(255),
    descripcion    varchar(1000)
);

create table rutinas (
    id          bigint generated by default as identity primary key,
    usuario_id  uuid,
    nombre      varchar(255),
    descripcion varchar(1000)
);

-- Ejercicios de cada rutina, con su objetivo (series x repeticiones, peso, descanso).
create table rutina_ejercicios (
    id            bigint generated by default as identity primary key,
    rutina_id     bigint references rutinas,
    ejercicio_id  bigint references ejercicios,
    orden         integer,
    series        integer,
    repeticiones  integer,
    peso_objetivo float(53),
    descanso      integer
);

create table entrenamientos (
    id               bigint generated by default as identity primary key,
    usuario_id       uuid not null,
    rutina_id        bigint references rutinas,
    nombre           varchar(255) not null,
    fecha            date not null,
    duracion_minutos integer,
    notas            varchar(1000),
    creado_en        timestamp(6) with time zone not null
);

create table series_entrenamiento (
    id               bigint generated by default as identity primary key,
    entrenamiento_id bigint not null references entrenamientos,
    ejercicio_id     bigint not null references ejercicios,
    orden            integer not null,
    numero_serie     integer not null,
    repeticiones     integer not null,
    peso             float(53) not null
);

-- Un perfil por usuario: su id es el mismo que el de auth.users de Supabase.
create table perfiles (
    usuario_id        uuid primary key,
    nombre_usuario    varchar(20) unique,
    sexo              varchar(20),
    fecha_nacimiento  date,
    altura_cm         integer,
    peso_kg           float(53),
    objetivo          varchar(30),
    peso_objetivo_kg  float(53),
    experiencia       varchar(20),
    dias_semana       integer,
    duracion_sesion   integer,
    lugar_entreno     varchar(30),
    actividad_diaria  varchar(20),
    lesiones          varchar(500),
    consentimiento_en timestamp(6),
    bienvenida_en     timestamp(6),
    creado_en         timestamp(6) not null,
    actualizado_en    timestamp(6)
);

-- Un registro de peso por usuario y día.
create table pesos_corporales (
    id         bigint generated by default as identity primary key,
    usuario_id uuid not null,
    fecha      date not null,
    peso_kg    float(53) not null,
    creado_en  timestamp(6) not null,
    unique (usuario_id, fecha)
);

-- Botón "Opinar" (versión alpha).
create table opiniones (
    id         bigint generated by default as identity primary key,
    usuario_id uuid not null,
    tipo       varchar(10) not null,
    texto      varchar(1000) not null,
    pagina     varchar(200),
    navegador  varchar(250),
    creado_en  timestamp(6) not null
);
